"""Render docs/output-reference.md, the output field reference, from the packaged output schemas.

    python tools/output_reference.py          # exit 1 if docs/output-reference.md is stale
    python tools/output_reference.py --write  # regenerate the marked section
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from agent_contribute import outputs  # noqa: E402

DOC = ROOT / 'docs' / 'output-reference.md'
START = '<!-- output-reference:start (generated by tools/output_reference.py; do not edit) -->'
END = '<!-- output-reference:end -->'


def kind(schema):
    if '$ref' in schema:
        return '`' + schema['$ref'].rsplit('/', 1)[-1] + '`'
    if 'anyOf' in schema:
        return ' or '.join(kind(option) for option in schema['anyOf'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' \\| '.join(json.dumps(value) for value in schema['enum'])
    types = schema.get('type', 'any')
    types = types if isinstance(types, list) else [types]
    if 'array' in types:
        types = [kind(schema['items']) + '[]' if item == 'array' else item for item in types]
    return ' or '.join(types)


def rows(schema, prefix=''):
    """Fields of one object, nested inline objects as dotted paths; $ref targets are listed once elsewhere."""
    for name, field in schema['properties'].items():
        path = prefix + name
        optional = '' if name in schema['required'] else ' (optional)'
        description = field.get('description', '').replace('|', '\\|')
        yield f'| `{path}` | {kind(field)}{optional} | {description} |'
        while field.get('type') == 'array' or field.get('type') == ['array', 'null']:
            field, path = field['items'], path + '[]'
        if 'properties' in field and field['properties']:
            yield from rows(field, path + '.')
        if isinstance(field.get('additionalProperties'), dict):
            yield f'| `{path}.*` | {kind(field["additionalProperties"])} | Keyed by remote name |'


def table(schema):
    if schema.get('properties'):
        return ['| Field | Type | Description |', '| --- | --- | --- |', *rows(schema)]
    return [f'Any JSON object ({schema.get("description", "")}).' if schema.get('additionalProperties') else kind(schema)]


def render():
    out, definitions = [], {}
    for name in outputs.SCHEMAS:
        schema = outputs.output_schema(name)
        definitions.update(schema.get('$defs', {}))
        out += ['', f'### `{name}`', '', f'`agent-contrib schema {name}` · {schema["description"]}', '']
        if 'anyOf' in schema:
            out.append('One of ' + ', '.join(kind(option) for option in schema['anyOf']) + '.')
        else:
            out += table(schema)
    out += ['', '### Definitions', '', 'Shared shapes referenced above; each name means the same shape in every schema.']
    for name, schema in sorted(definitions.items()):
        out += ['', f'#### `{name}`', '']
        if schema.get('description'):
            out += [schema['description'], '']
        out += table(schema)
    return '\n'.join([START, *out, '', END])


def current():
    text = DOC.read_text('utf-8')
    return text, text[text.index(START):text.index(END) + len(END)]


def main(argv):
    text, section = current()
    if argv == ['--write']:
        DOC.write_text(text.replace(section, render()), 'utf-8')
        return 0
    return 0 if section == render() else 1


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
